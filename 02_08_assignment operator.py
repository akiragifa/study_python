"""
赋值运算符

| 运算符 | 含义 | 示例 | 相当于 |
|---|---|---|---|
| `=` | 直接赋值 | `x = 5` | 把 `5`赋给 `x` |
| `+=` | 加后赋值 | `x += 2` | `x = x + 2` |
| `-=` | 减后赋值 | `x -= 2` | `x = x - 2` |
| `*=` | 乘后赋值 | `x *= 2` | `x = x * 2` |
| `/=` | 除后赋值 | `x /= 2` | `x = x / 2` |
| `//=` | 整除后赋值 | `x //= 2` | `x = x // 2` |
| `%=` | 取余后赋值 | `x %= 2` | `x = x % 2` |
| `**=` | 幂运算后赋值 | `x **= 2` | `x = x ** 2` |
"""

a = 1
a += 1
print(a)    # 2

