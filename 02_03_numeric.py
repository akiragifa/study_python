"""
numeric_types

| 类型   | 英文                    | Python类型  | 示例     | 说明      |
| ------ | ----------------------- | ---------- | -------- | ------- |
| 整数   | Integer                 | `int`      | `10`     | 不带小数的数字 |
| 浮点数 | Floating-point number   | `float`    | `3.14`    | 带小数的数字  |
| 复数   | Complex number          | `complex`  | `3+4j`    | 实部+虚部   |
"""

