"""
交集和并集

&：交集
|：并集

"""

a = {1, 2, 3, 4}
b = {3, 4, 5, 6}
c = {5, 6, 7, 8}

print(a & b)    # {3, 4}
print(a & c)    # set() ，空集合

print(a | b)    # {1, 2, 3, 4, 5, 6}